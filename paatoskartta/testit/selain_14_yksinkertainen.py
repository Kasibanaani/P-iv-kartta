# Yksinkertainen päätöspuu, uusi vaihtoehto käytön aikana, alapalkki, i-ohje ja kelluva ilmoitus (versio 14).
import asyncio, json, os
from playwright.async_api import async_playwright
U='file://'+os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)),'..','index.html'))
def check(label,cond):
    print(('ok    ' if cond else 'VIRHE ')+label)
    if not cond: errs.append('odotus: '+label)
errs=[]
async def run(p,w):
    b=await p.chromium.launch(); ctx=await b.new_context(viewport={'width':w,'height':760},device_scale_factor=1)
    pg=await ctx.new_page(); pg.on('pageerror',lambda e: errs.append(str(e)))
    await pg.goto(U); await pg.wait_for_timeout(200)
    store=lambda q: pg.evaluate("(function(){var d=JSON.parse(localStorage.getItem('paatoskartta:v1')),t=d.trees[d.trees.length-1];return %s})()" % q)
    rows=lambda: pg.evaluate("[...document.querySelectorAll('#use-list .row')].filter(b=>!b.hidden).map(b=>b.querySelector('.t').textContent+(b.classList.contains('sel')?'[v]':'')+(b.classList.contains('rec')?'[s'+b.querySelector('.tag').textContent.replace('suositus','')+']':'')).join(', ')")
    async def add(n):
        if not await pg.is_visible('#use-addinp'): await pg.click('#use-addlink')
        await pg.keyboard.type(n); await pg.keyboard.press('Enter'); await pg.wait_for_timeout(60)
    print('--- leveys',w)
    check('yksinkertainen on uuden puun oletus', await pg.get_attribute('#first-kind [data-sk="s"]','aria-pressed')=='true')
    await pg.fill('#p-use input','Ilta'); await pg.click('#p-use .btn:has-text("Luo")'); await pg.wait_for_timeout(150)
    check('puu on yksinkertainen', await store('t.simple')==True)
    # rakennetaan puu käyttäessä
    await add('Kotona'); await add('Ulkona')
    check('kenttä pysyy auki ja kohdistettuna', await pg.evaluate("document.activeElement.id")=='use-addinp')
    await pg.keyboard.press('Escape'); await pg.wait_for_timeout(60)
    await pg.click('#use-list .row:has-text("Ulkona")'); await pg.wait_for_timeout(80)
    check('linkki kertoo, minkä perään', 'Ulkona' in await pg.inner_text('#use-addlink'))
    await add('Lenkki'); await add('Kahvila'); await pg.keyboard.press('Escape'); await pg.wait_for_timeout(60)
    r=await rows(); print('  rivit:', r)
    check('uudet ulkona-haaraan ja korostettuina', r=='Kotona, Ulkona[v], Lenkki[s], Kahvila[s]')
    check('ilmoitus kelluu', await pg.is_visible('#info') and 'Lisätty' in await pg.inner_text('#info-text'))
    check('säännöt tallessa', await store('JSON.stringify(t.rec)')==json.dumps({"o2":["o3","o4"]}).replace(' ',''))
    await pg.click('#use-list .row:has-text("Kotona")'); await add('Elokuva'); await pg.keyboard.press('Escape'); await pg.wait_for_timeout(60)
    r=await rows(); print('  rivit:', r)
    check('kaikki näkyvät aina, Elokuva kotona-haaraan', r=='Kotona[v], Elokuva[s], Ulkona[v], Lenkki[s], Kahvila[s]')
    await pg.click('#use-addlink'); await pg.keyboard.type('lenkki'); await pg.keyboard.press('Enter'); await pg.wait_for_timeout(60)
    check('sama nimi torjutaan varoituksena', 'jo listassa' in await pg.inner_text('#info-text')); await pg.fill('#use-addinp',''); await pg.keyboard.press('Escape')
    # ei pomppimista: napautus ei siirrä rivejä
    pos=lambda: pg.evaluate("[...document.querySelectorAll('#use-list .row')].map(b=>Math.round(b.getBoundingClientRect().top)).join(',')")
    a=await pos(); await pg.click('#use-list .row:has-text("Lenkki")'); await pg.wait_for_timeout(80); bb=await pos()
    check('valinta ei siirrä rivejä', a==bb)
    await pg.screenshot(path='pt14_%d_kaytto.png'%w)
    simple_rows=await rows()
    await pg.click('#title'); await pg.click('#ts-list [data-edit]'); await pg.wait_for_timeout(150)
    await pg.click('#ns-kind [data-sk="f"]'); await pg.wait_for_timeout(100)
    check('vaihto monipuoliseksi', await store('t.simple')==None)
    await pg.mouse.click(5,5); await pg.wait_for_timeout(150)
    r=await rows(); print('  monipuolisena:', r)
    check('monipuolisena kaikki näkyvät, koska yksinkertaisessa ei ole ehtoja', r.count(',')==4 and await store('JSON.stringify(t.suf)')=='{}')
    await pg.click('#title'); await pg.click('#ts-list [data-edit]'); await pg.wait_for_timeout(150); await pg.click('#ns-kind [data-sk="s"]'); await pg.mouse.click(5,5); await pg.wait_for_timeout(150)
    check('takaisin yksinkertaiseksi, ennallaan', await rows()==simple_rows)
    # osiovalikko ja opetus
    await pg.click('#secbtn'); await pg.wait_for_timeout(60)
    check('osiovalikko auki', await pg.is_visible('#secmenu'))
    await pg.screenshot(path='pt14_%d_valikko.png'%w)
    await pg.click('#secmenu [data-tab="teach"]'); await pg.wait_for_timeout(150)
    check('opetuksessa vain + Vaihtoehto', await pg.is_visible('#addplain') and not await pg.is_visible('#addcond'))
    lst=await pg.evaluate("[...document.querySelectorAll('#teach-list .row')].map(b=>b.querySelector('small').textContent).join(' | ')"); print('  lista:', lst)
    check('yhteenveto suosituksista', 'suosittelee: Lenkki, Kahvila' in lst)
    await pg.click('#teach-list .row:has-text("Kotona")'); await pg.wait_for_timeout(150)
    check('tekijäsivulla ei tähtiä eikä kiertoa', await pg.evaluate("document.querySelectorAll('#p-teach .star').length")==0)
    await pg.click('#simple-list .row:has-text("Kahvila")'); await pg.wait_for_timeout(60)
    check('napautus merkitsee suosituksen', await store('JSON.stringify(t.rec.o1)')=='["o5","o4"]')
    await pg.click('#simple-list .row:has-text("Kahvila")'); await pg.wait_for_timeout(60)
    check('uusi napautus poistaa', await store('JSON.stringify(t.rec.o1)')=='["o5"]')
    await pg.click('#item-addlink'); await pg.keyboard.type('Kirja'); await pg.keyboard.press('Enter'); await pg.wait_for_timeout(80)
    check('uusi suositeltu tekijäsivulta', 'Kirja' in await pg.inner_text('#teach-inc'))
    await pg.keyboard.press('Escape')
    await pg.screenshot(path='pt14_%d_tekija.png'%w)
    # i-ohje: ulkopuolinen napautus vain sulkee
    await pg.click('#helpbtn'); await pg.wait_for_timeout(60)
    check('ohje aukeaa', await pg.is_visible('.pkd'))
    await pg.screenshot(path='pt14_%d_ohje.png'%w)
    before=await store('JSON.stringify(t.rec)')
    box=await pg.evaluate("(function(){var q=document.querySelector('#simple-list .row:last-child').getBoundingClientRect();return [q.x+30,q.y+20]})()")
    await pg.mouse.click(box[0],box[1]); await pg.wait_for_timeout(80)
    check('ulkopuolinen napautus sulki ohjeen eikä merkinnyt riviä', not await pg.is_visible('.pkd') and before==await store('JSON.stringify(t.rec)'))
    # muokkausikkunassa ei lajia eikä pullonkaulaa
    await pg.click('#item-edit'); await pg.wait_for_timeout(100)
    check('muokkausikkunassa ei lajia eikä pullonkaulaa', not await pg.is_visible('#os-kind') and not await pg.is_visible('#os-bn'))
    await pg.mouse.click(5,5); await pg.wait_for_timeout(100)
    # seuranta ja pikavienti
    await pg.click('#secbtn'); await pg.click('#secmenu [data-tab="stat"]'); await pg.wait_for_timeout(150)
    st=await pg.inner_text('#p-stat'); check('seuranta toimii', 'Valittu' in st)
    check('vientipiste näkyy', await pg.is_visible('#setdot'))
    ow=await pg.evaluate("[document.documentElement.scrollWidth,document.getElementById('main').scrollWidth,document.getElementById('main').clientWidth]")
    check('ei vaakavieritystä %s'%ow, ow[0]<=w and ow[1]<=ow[2])
    hb=await pg.evaluate("document.getElementById('top').offsetHeight"); print('  yläpalkin korkeus', hb)
    # tekstinä ja takaisin
    txt=await pg.evaluate("(function(){var d=JSON.parse(localStorage.getItem('paatoskartta:v1'));return d.trees[0].simple})()")
    check('tallennettu simple', txt==True)
    await b.close()
async def main():
    async with async_playwright() as p:
        for w in (390,320): await run(p,w)
    print('errs', errs)
asyncio.run(main())
